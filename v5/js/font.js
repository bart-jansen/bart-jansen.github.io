/** Everything we cannot draw becomes a middle dot rather than a hole. */
const FALLBACK = '·';

const cache = new Map();

function glyph(ch, colour) {
  const key = ch + '\u0000' + colour;
  let c = cache.get(key);
  if (c) return c;
  const rows = G[ch] || G[FALLBACK];
  const s = surface(GLYPH_W, GLYPH_H);
  s.ctx.fillStyle = colour;
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y];
    for (let x = 0; x < GLYPH_W; x++) if (row[x] === '#') s.ctx.fillRect(x, y, 1, 1);
  }
  cache.set(key, s.canvas);
  return s.canvas;
}

/** Normalise so accented and typographic characters still render. */
const FOLD = {
  '—': '-', '–': '-', '‑': '-', '’': "'", '‘': "'", '“': '"', '”': '"',
  'é': 'E', 'è': 'E', 'ë': 'E', 'ê': 'E', 'á': 'A', 'à': 'A', 'ä': 'A',
  'í': 'I', 'ï': 'I', 'ó': 'O', 'ö': 'O', 'ú': 'U', 'ü': 'U', 'ç': 'C', 'ñ': 'N',
};

export function normalise(text) {
  let out = '';
  for (const raw of String(text)) out += FOLD[raw] || raw;
  return out.toUpperCase();
}

/** Width of a string in device pixels at the given scale. */
export function measure(text, scale = 1) {
  const n = normalise(text).length;
  return n === 0 ? 0 : (n * (GLYPH_W + TRACKING) - TRACKING) * scale;
}

export const lineHeight = (scale = 1) => GLYPH_H * scale;

/**
 * Draw a single line. `align` is 'left' | 'centre' | 'right'; `shadow` paints a
 * one-pixel drop first, which is what makes the HUD read on a bright sky.
 */
export function text(ctx, str, x, y, opts = {}) {
  const { scale = 1, colour = '#ffffff', align = 'left', shadow = null } = opts;
  const s = normalise(str);
  const w = measure(s, scale);
  let ox = x;
  if (align === 'centre') ox = Math.round(x - w / 2);
  else if (align === 'right') ox = Math.round(x - w);
  ox = Math.round(ox);
  const oy = Math.round(y);
  const step = (GLYPH_W + TRACKING) * scale;
  if (shadow) {
    for (let i = 0; i < s.length; i++) {
      if (s[i] === ' ') continue;
      ctx.drawImage(glyph(s[i], shadow), ox + i * step + scale, oy + scale, GLYPH_W * scale, GLYPH_H * scale);
    }
  }
  for (let i = 0; i < s.length; i++) {
    if (s[i] === ' ') continue;
    ctx.drawImage(glyph(s[i], colour), ox + i * step, oy, GLYPH_W * scale, GLYPH_H * scale);
  }
  return w;
}

/** Greedy word wrap, measured in the same units `text` draws in. */
export function wrap(str, maxWidth, scale = 1) {
  const words = String(str).split(/\s+/).filter(Boolean);
  const lines = [];
  let line = '';
  for (const word of words) {
    const next = line ? line + ' ' + word : word;
    if (measure(next, scale) <= maxWidth || !line) line = next;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}
